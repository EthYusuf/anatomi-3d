const EN_ORD: Record<string, number> = {
  first: 1, second: 2, third: 3, fourth: 4, fifth: 5, sixth: 6, seventh: 7, eighth: 8, ninth: 9, tenth: 10, eleventh: 11, twelfth: 12,
};

type Rule = [RegExp, (m: RegExpMatchArray) => string];
const RULES: Rule[] = [
  [/^vertebra ([ctl])(\d+)$/, (m) => `${m[1].toUpperCase()}${m[2]} omuru`],
  [/^(\w+) rib$/, (m) => `${EN_ORD[m[1]]}. kaburga`],
  [/^costal cartilage of (\w+) rib$/, (m) => `${EN_ORD[m[1]]}. kaburga kıkırdağı`],
  [/^(\w+) metacarpal bone$/, (m) => `${EN_ORD[m[1]]}. metakarp kemiği`],
  [/^(\w+) metatarsal bone$/, (m) => `${EN_ORD[m[1]]}. metatars kemiği`],
  [
    /^(distal|middle|proximal) phalanx of (\w+) finger of (hand|foot)$/,
    (m) =>
      `${m[3] === 'hand' ? 'El' : 'Ayak'} ${EN_ORD[m[2]]}. parmak ${{ distal: 'distal', middle: 'orta', proximal: 'proksimal' }[m[1]]} falanksı`,
  ],
  [
    /^(upper|lower) (medial|lateral) incisor$/,
    (m) => `${m[1] === 'upper' ? 'Üst' : 'Alt'} ${m[2] === 'medial' ? 'orta' : 'yan'} kesici diş`,
  ],
  [/^(upper|lower) canine$/, (m) => `${m[1] === 'upper' ? 'Üst' : 'Alt'} köpek dişi`],
  [/^(upper|lower) (first|second) premolar$/, (m) => `${m[1] === 'upper' ? 'Üst' : 'Alt'} ${EN_ORD[m[2]]}. küçük azı`],
  [/^(upper|lower) (first|second|third) molar tooth$/, (m) => `${m[1] === 'upper' ? 'Üst' : 'Alt'} ${EN_ORD[m[2]]}. büyük azı`],
];

/** Yapının Türkçe adı (varsa) */
export function turkishName(en: string): string | undefined {
  const k = en.toLowerCase();
  const n = NAMES[k];
  if (n) return n;
  for (const [re, f] of RULES) {
    const m = k.match(re);
    if (m) return f(m);
  }
  return undefined;
}

